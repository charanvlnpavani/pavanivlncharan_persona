import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "../config/env";

/**
 * File storage behind a small interface. The local-disk driver is used in
 * development and on hosts with a persistent volume. A cloud driver (S3 / R2)
 * can implement the same four methods without touching any caller.
 */
export interface Storage {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  /** Absolute directory for a public area, used to serve uploads statically. */
  root(area: "uploads" | "resumes"): string;
}

/** Keys are generated by us, but never trust them: block path traversal. */
function safeKey(key: string) {
  if (!/^(uploads|resumes)\/[A-Za-z0-9._-]+$/.test(key)) throw new Error(`Invalid storage key: ${key}`);
  return key;
}

class LocalStorage implements Storage {
  constructor(private readonly base: string) {}

  root(area: "uploads" | "resumes") {
    return path.join(this.base, area);
  }

  async put(key: string, data: Buffer) {
    const file = path.join(this.base, safeKey(key));
    await mkdir(path.dirname(file), { recursive: true });
    // Write to a temp file then rename, so readers never see a half-written file.
    const tmp = `${file}.${process.pid}.tmp`;
    await writeFile(tmp, data);
    await rename(tmp, file);
  }

  get(key: string) {
    return readFile(path.join(this.base, safeKey(key)));
  }

  async delete(key: string) {
    await rm(path.join(this.base, safeKey(key)), { force: true });
  }
}

export const storage: Storage = new LocalStorage(path.resolve(env.STORAGE_DIR));
